using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;
using CoreEngine.GameData;
using CoreEngine.Helpers;

namespace CoreEditor.GameData
{
    public static class KeyClassGenerator
    {
        internal static void Generate(ITableSetter tableSetter, List<string> rawKeys)
        {
            if (tableSetter is not ScriptableObject tableSO)
                throw new ArgumentException("[KeyClassGenerator] tableSetter가 ScriptableObject가 아닙니다.");

            if (rawKeys == null || rawKeys.Count == 0)
                return;

            // 1. Table.cs 원본 스크립트 경로 및 타입 정보 추출
            Type tableType = tableSO.GetType();
            MonoScript tableScript = MonoScript.FromScriptableObject(tableSO);
            if (tableScript == null)
                throw new Exception($"[KeyClassGenerator] '{tableType.Name}'의 원본 C# 스크립트를 찾을 수 없습니다.");

            string scriptPath = AssetDatabase.GetAssetPath(tableScript);
            string directory = Path.GetDirectoryName(scriptPath);

            if (string.IsNullOrEmpty(directory))
                throw new Exception($"[KeyClassGenerator] '{tableType.Name}' 스크립트의 디렉터리 경로를 확인할 수 없습니다.");

            // 2. 파일명 및 클래스명 설정 ({TableName}Keys)
            string className = $"{tableType.Name}Keys";
            string outputPath = Path.Combine(directory, $"{className}.cs").Replace('\\', '/');
            string namespaceName = tableType.Namespace;

            // 3. C# 코드 빌드
            string codeContent = BuildClassContent(namespaceName, className, rawKeys);

            // 기존 파일과 내용이 완전히 동일하면 불필요한 재컴파일 방지를 위해 덮어쓰지 않음
            if (File.Exists(outputPath) && File.ReadAllText(outputPath, Encoding.UTF8) == codeContent)
                return;

            File.WriteAllText(outputPath, codeContent, Encoding.UTF8);
            AssetDatabase.ImportAsset(outputPath, ImportAssetOptions.ForceUpdate);
        }

        private static string BuildClassContent(string namespaceName, string className, List<string> rawKeys)
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("// Auto-generated by CoreEditor. Do not modify manually.");
            sb.AppendLine();

            bool hasNamespace = !string.IsNullOrEmpty(namespaceName);
            string indent = hasNamespace ? "    " : "";

            if (hasNamespace)
            {
                sb.AppendLine($"namespace {namespaceName}");
                sb.AppendLine("{");
            }

            sb.AppendLine($"{indent}public static class {className}");
            sb.AppendLine($"{indent}{{");

            HashSet<string> usedIdentifiers = new HashSet<string>();

            foreach (string rawKey in rawKeys)
            {
                if (string.IsNullOrEmpty(rawKey)) continue;

                ulong hashedPK = HashHelper.StringToId(rawKey);
                string identifier = SanitizeIdentifier(rawKey);

                // 변환된 변수명이 중복될 경우 접미사 추가
                string uniqueIdentifier = identifier;
                int suffix = 1;
                while (!usedIdentifiers.Add(uniqueIdentifier))
                {
                    uniqueIdentifier = $"{identifier}_{suffix++}";
                }

                sb.AppendLine($"{indent}    /// <summary> Key: \"{rawKey}\" </summary>");
                sb.AppendLine($"{indent}    public const ulong {uniqueIdentifier} = {hashedPK}UL;");
            }

            sb.AppendLine($"{indent}}}");

            if (hasNamespace)
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }

        /// <summary>
        /// 원본 키 문자열을 유효한 C# 상수 식별자 이름으로 변환합니다.
        /// </summary>
        private static string SanitizeIdentifier(string rawKey)
        {
            // 구분자(KeySeparator)를 언더스코어로 우선 치환
            string replaced = rawKey.Replace(Constants.KeySeparator, "_");
            StringBuilder sb = new StringBuilder(replaced.Length + 1);

            for (int i = 0; i < replaced.Length; i++)
            {
                char c = replaced[i];
                if (char.IsLetterOrDigit(c) || c == '_')
                {
                    sb.Append(c);
                }
                else
                {
                    sb.Append('_');
                }
            }

            if (sb.Length == 0)
                return "_EmptyKey";

            // C# 식별자는 숫자로 시작할 수 없으므로 앞에 '_' 추가
            if (char.IsDigit(sb[0]))
            {
                sb.Insert(0, '_');
            }

            return sb.ToString();
        }
    }
}